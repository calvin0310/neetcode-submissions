func countBits(n int) []int {
	dp := make([]int, n+1) // 長度要是 n+1，因為包含 0

	for i := 0; i <= n; i++ {
		dp[i] = dp[i >> 1] + (i & 1) 
		// dp[i]代表i的二進制有幾個1，例如: n=4, dp[4]=dp[2]+0=1+0=1 (100)
		// 我們觀察得知如果i是偶數，除2，1的數量也是一樣，4(100)//2=2(10)，都是1
		// 如果i是奇數，i=5(101)//2=2(10) 會少掉最後一位數的1，所以要把最後一位數加回來 i&1
		//i >> 1 相當於 //2，i & 1 則是判斷個位數最後一位數是否為奇數，是的話就是1，偶數就是0
	}
	return dp
}
